import assert from 'node:assert/strict';
import {adapterMeta,connectionQuality,CameraService} from '../js/camera/service.js';
assert.equal(adapterMeta('dji_osmo').shortName,'DJI');
assert.equal(adapterMeta('gopro_open').defaultName,'GoPro HERO');
assert.deepEqual(connectionQuality({connected:false}),{label:'Getrennt',state:'muted'});
assert.equal(connectionQuality({connected:true,lastStatusAt:Date.now(),statusFailures:0,reconnects:0}).state,'ok');
assert.equal(connectionQuality({connected:true,lastStatusAt:Date.now(),statusFailures:1,reconnects:0}).state,'warn');
const s=new CameraService({adapter:'gopro_open',statusIntervalMs:12000});
assert.equal(s.meta.shortName,'GoPro');
assert.equal(s.snapshot().connected,false);
s.configure({adapter:'dji_osmo',statusIntervalMs:15000});
assert.equal(s.meta.shortName,'DJI');
console.log('0.4.0 RC4 camera service regression: OK');
