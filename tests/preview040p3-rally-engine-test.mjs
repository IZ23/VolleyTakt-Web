import {createRallyController,automaticPointFor} from '../js/scouting/rally.js';
const ok=(x,m)=>{if(!x)throw new Error(m)};
let seq=0;
const state={servingSide:'them',currentRallyId:'',currentRallyNo:0,currentRallySeq:0,rallyCounter:0,rallyStartServing:'',currentRallyPhase:'',currentTransitionNo:1,lastActionSide:''};
const rally=createRallyController({getState:()=>state,newId:p=>`${p}_${++seq}`});
let m=rally.nextRallyMeta('action');
ok(m.rally_no==='1'&&m.rally_sequence==='1','first rally metadata');
ok(state.currentRallyPhase==='K1','opponent serve starts K1');
let c=rally.contextForAction('opponent');ok(c.rally_phase==='K1'&&c.transition_no==='1','K1 context');
rally.markActionSide('opponent');c=rally.contextForAction('own');ok(c.transition_no==='2'&&c.rally_phase==='K3','transition to K3');
rally.markActionSide('own');c=rally.contextForAction('opponent');ok(c.transition_no==='2','opponent action does not spuriously increment own transition');
rally.closeActiveRally();ok(!state.currentRallyId&&state.currentRallyNo===0&&state.currentTransitionNo===1,'close reset');
state.servingSide='us';m=rally.nextRallyMeta('action');ok(state.currentRallyPhase==='K2','own serve starts K2');
ok(automaticPointFor('own','Aufschlag','=')==='them','own serve error');
ok(automaticPointFor('opponent','Aufschlag','=')==='us','opponent serve error');
ok(automaticPointFor('own','Angriff','#')==='us','own attack terminal');
ok(automaticPointFor('opponent','Block','#')==='them','opponent block terminal');
ok(automaticPointFor('own','Annahme','#')==='','reception perfect non-terminal');
ok(automaticPointFor('own','Abwehr','#')==='','defense perfect non-terminal');
ok(automaticPointFor('own','Zuspiel','#')==='','set perfect non-terminal');
console.log('Preview3 rally engine checks OK');
