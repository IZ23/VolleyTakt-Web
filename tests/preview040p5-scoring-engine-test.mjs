import {scorePointTransition,winningSideForTarget,setWinTransition} from '../js/scouting/scoring.js';
const need=(v,m)=>{if(!v)throw new Error(m)};
let t=scorePointTransition({winner:'us',scoreUs:10,scoreThem:9,servingSide:'them'});
need(t.scoreUs===11&&t.scoreThem===9,'own point score');
need(t.servingBefore==='them'&&t.servingAfter==='us'&&t.sideout===true,'sideout transition');
t=scorePointTransition({winner:'them',scoreUs:24,scoreThem:24,servingSide:'them'});
need(t.scoreUs===24&&t.scoreThem===25&&!t.sideout,'serving team point');
need(winningSideForTarget(25,23,25)==='us','set winner us');
need(winningSideForTarget(25,24,25)==='','two point lead required');
need(winningSideForTarget(14,16,15)==='them','target 15 deuce winner');
const s=setWinTransition({winner:'them',setWinsUs:1,setWinsThem:2});
need(s.setWinsUs===1&&s.setWinsThem===3,'set win transition');
console.log('Preview5 scoring engine checks OK');
