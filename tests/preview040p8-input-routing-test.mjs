import assert from 'node:assert/strict';
import {COMMANDS} from '../js/app/commands.js';
import {normalizeShortcutKey,shortcutKeyLabel,shortcutActionForKey,commandForShortcutAction,createEdgeSwipeRouter} from '../js/app/input-routing.js';

assert.equal(normalizeShortcutKey('a'),'A');
assert.equal(normalizeShortcutKey('Backspace'),'Backspace');
assert.equal(shortcutKeyLabel(' '),'Leertaste');
const shortcuts={'position.1':'1','action.attack':'A','quality.hash':'*','rally.own':'P','substitution':'W','libero':'L','rotation':'R','undo':'Backspace','cancel':'Escape'};
assert.equal(shortcutActionForKey(shortcuts,'a'),'action.attack');
assert.deepEqual(commandForShortcutAction('position.1'),{command:COMMANDS.SELECT_POSITION,position:1});
assert.deepEqual(commandForShortcutAction('action.attack'),{command:COMMANDS.SELECT_ACTION,action:'Angriff'});
assert.deepEqual(commandForShortcutAction('quality.hash'),{command:COMMANDS.SELECT_QUALITY,quality:'#'});
assert.deepEqual(commandForShortcutAction('rally.own'),{command:COMMANDS.AWARD_POINT_US});
assert.deepEqual(commandForShortcutAction('substitution'),{command:COMMANDS.SUBSTITUTION});
assert.deepEqual(commandForShortcutAction('libero'),{command:COMMANDS.LIBERO});
assert.deepEqual(commandForShortcutAction('rotation'),{command:COMMANDS.ROTATE,direction:1});
assert.deepEqual(commandForShortcutAction('undo'),{command:COMMANDS.UNDO});
assert.deepEqual(commandForShortcutAction('cancel'),{command:COMMANDS.CANCEL});
assert.equal(commandForShortcutAction('unknown'),null);
const swipe=createEdgeSwipeRouter();
assert.equal(swipe.pointerDown({pointerType:'touch',clientX:10,clientY:100}),true);
assert.equal(swipe.pointerUp({clientX:90,clientY:120}),true);
assert.equal(swipe.pointerDown({pointerType:'mouse',clientX:10,clientY:100}),false);
assert.equal(swipe.pointerUp({clientX:100,clientY:100}),false);
assert.equal(swipe.pointerDown({pointerType:'touch',clientX:40,clientY:100}),false);
assert.equal(swipe.pointerDown({pointerType:'touch',clientX:10,clientY:100}),true);
assert.equal(swipe.pointerUp({clientX:60,clientY:200}),false);
console.log('preview040p8-input-routing-test: ok');
